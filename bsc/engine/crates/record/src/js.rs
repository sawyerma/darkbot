//! The schema tables of the records the DRY's JavaScript tools read or
//! write, generated for `bsc/tools/dbrec.cjs`. The Rust schemas stay the
//! single authority: the committed `bsc/tools/dbrec_schemas.generated.cjs`
//! must equal `module()`, which a test checks, and every record the tools
//! write is decoded fail-closed by Rust.

use crate::schema::g06a;
use crate::{Kind, Presence, Schema};
use std::fmt::Write as _;

/// The schemas the JavaScript tools use.
pub fn exported() -> [&'static Schema; 5] {
    [
        &g06a::preflight::SCHEMA,
        &g06a::local_simulation::NATIVE,
        &g06a::economics::NATIVE,
        &g06a::economics::PRIVATE,
        &g06a::launch_path::SCHEMA,
    ]
}

fn kind(k: Kind) -> &'static str {
    match k {
        Kind::Bool => "Bool",
        Kind::U64 => "U64",
        Kind::I64 => "I64",
        Kind::U256 => "U256",
        Kind::Address => "Address",
        Kind::B256 => "B256",
        Kind::Bytes => "Bytes",
        Kind::Text => "Text",
        Kind::Nested => "Nested",
    }
}

fn presence(p: Presence) -> &'static str {
    match p {
        Presence::Required => "Required",
        Presence::Optional => "Optional",
        Presence::Repeated => "Repeated",
    }
}

/// The generated JavaScript module.
pub fn module() -> String {
    let mut out = String::from(
        "// GENERATED by `cargo run -p darkbot-bsc-record --bin dbrec_js_schemas` from the\n\
         // Rust schemas in bsc/engine/crates/record (the authority). Do not edit: the\n\
         // record crate test `js_schema_module_is_current` fails when this file is stale.\n\
         'use strict';\n\nmodule.exports = {\n",
    );
    for schema in exported() {
        let _ = writeln!(
            out,
            "  '{}': {{ recordType: {}, schemaVersion: {}, fields: [",
            schema.name, schema.record_type, schema.schema_version
        );
        for f in schema.fields {
            let _ = writeln!(
                out,
                "    [{}, '{}', '{}', '{}', {}],",
                f.tag,
                f.name,
                kind(f.kind),
                presence(f.presence),
                f.max_len
            );
        }
        out.push_str("  ] },\n");
    }
    out.push_str("};\n");
    out
}

#[cfg(test)]
mod tests {
    #[test]
    fn js_schema_module_is_current() {
        let committed = include_str!("../../../../tools/dbrec_schemas.generated.cjs");
        assert_eq!(
            committed,
            super::module(),
            "regenerate with dbrec_js_schemas"
        );
        for schema in super::exported() {
            assert!(
                schema.fields.iter().all(|f| f.nested.is_none()),
                "{}: the JS codec has no nested records",
                schema.name
            );
        }
    }
}
