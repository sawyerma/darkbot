"""Small policy interface; StateOwner retains all shared execution and safety state."""
from typing import Protocol, Any
from decimal import Decimal
from darkbot.solana_pump.strategy import EntryVerdict


class StrategyPolicy(Protocol):
    strategy_id: str

    def on_create(self, owner: Any, mint: str, raw: Any, envelope: Any, decode_done: int) -> None: ...
    def on_events(self, owner: Any, result: Any, raw: Any, envelope: Any) -> None: ...
    def admission(self, state: Any, **checks: Any) -> EntryVerdict: ...
    def creator_exit_enabled(self) -> bool: ...
    def target_reached(self, value: int | None, entry_cost: int, target: Decimal) -> bool: ...
    def stop_reached(self, value: int | None, entry_cost: int) -> bool: ...
    def cancel_entry_if_creator_sold_before_fill(self) -> bool: ...
